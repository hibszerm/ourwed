export function summarizeK3HelpCorpus() {
  const byDomain: Record<string, number> = {}
  for (const t of K3_PRODUCT_HELP_CORPUS) {
    byDomain[t.domain] = (byDomain[t.domain] ?? 0) + 1
  }
  return {
    turns: K3_PRODUCT_HELP_CORPUS.length,
    supported: K3_PRODUCT_HELP_CORPUS.filter((t) => t.expectedCapabilityIds.length > 0).length,
    negative: K3_PRODUCT_HELP_CORPUS.filter((t) => t.kind === 'negative').length,
    byDomain,
  }
}
